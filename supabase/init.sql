-- ── 1) 清理旧的测试数据和旧版函数 ────────────────────────────────────

drop table if exists public.purchase_order_items cascade;
drop table if exists public.purchase_orders cascade;
drop table if exists public.stock_records cascade;
drop table if exists public.reagents cascade;
drop table if exists public.platform_admins cascade;
drop table if exists public.tenant_invites cascade;
drop table if exists public.tenant_members cascade;
drop table if exists public.tenants cascade;

do $$
declare fn record;
begin
  for fn in
    select p.oid::regprocedure as signature
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname in (
        'is_tenant_member', 'is_tenant_admin', 'is_platform_admin', 'claim_default_tenant',
        'create_tenant', 'create_platform_tenant', 'create_tenant_invite', 'accept_tenant_invite',
        'submit_stock_batch', 'create_restock_order', 'receive_purchase_order', 'save_reagent'
      )
  loop
    execute format('drop function %s cascade', fn.signature);
  end loop;
end $$;

-- ── 2) 租户（检验科）、成员、邀请码 ──────────────────────────────────

create table public.tenants (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  code        text not null,
  status      text not null default 'active' check (status in ('active', 'disabled')),
  created_by  uuid references auth.users(id) on delete set null,
  created_at  timestamptz not null default now()
);
create unique index tenants_code_lower_idx on public.tenants (lower(code));

create table public.tenant_members (
  tenant_id  uuid not null references public.tenants(id) on delete cascade,
  user_id    uuid not null references auth.users(id) on delete cascade,
  role       text not null default 'employee' check (role in ('admin', 'employee')),
  created_at timestamptz not null default now(),
  primary key (tenant_id, user_id)
);
-- Enforce the one-account-one-lab rule in the database, including concurrent invite claims.
create unique index tenant_members_one_tenant_per_user_idx on public.tenant_members (user_id);

create table public.tenant_invites (
  id          uuid primary key default gen_random_uuid(),
  tenant_id   uuid not null references public.tenants(id) on delete cascade,
  code        text not null unique,
  role        text not null default 'employee' check (role in ('admin', 'employee')),
  created_by  uuid not null references auth.users(id) on delete restrict,
  expires_at  timestamptz not null default (now() + interval '7 days'),
  used_by     uuid references auth.users(id) on delete set null,
  used_at     timestamptz,
  created_at  timestamptz not null default now()
);
create index tenant_invites_tenant_idx on public.tenant_invites (tenant_id, created_at desc);

-- 平台管理员：只有这里的账号可以开通新检验科（商用授权入口）。
create table public.platform_admins (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_platform_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.platform_admins pa where pa.user_id = auth.uid());
$$;

