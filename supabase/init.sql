-- ── 7) 业务 RPC（函数内再次校验成员/管理员身份）──────────────────────

create or replace function public.submit_stock_batch(
  p_tenant_id uuid, p_type text, p_operator text, p_department text, p_reason text, p_items jsonb
)
returns integer
language plpgsql security definer set search_path = public
as $$
declare
  item jsonb;
  reagent_row public.reagents;
  item_quantity integer;
  total integer := 0;
begin
  if not public.is_tenant_member(p_tenant_id) then raise exception '无权访问该检验科'; end if;
  if p_type not in ('in', 'out') then raise exception '无效的库存操作'; end if;
  for item in select * from jsonb_array_elements(p_items) loop
    item_quantity := (item->>'quantity')::integer;
    if item_quantity is null or item_quantity <= 0 then raise exception '数量必须大于 0'; end if;
    select * into reagent_row from public.reagents
      where id = (item->>'reagent_id')::bigint and tenant_id = p_tenant_id for update;
    if reagent_row.id is null then raise exception '试剂不存在或不属于当前检验科'; end if;
    if p_type = 'out' and reagent_row.stock_quantity < item_quantity then
      raise exception '出库数量超过库存：%', reagent_row.name;
    end if;
    update public.reagents
      set stock_quantity = stock_quantity + case when p_type = 'in' then item_quantity else -item_quantity end
      where id = reagent_row.id and tenant_id = p_tenant_id;
    insert into public.stock_records
      (tenant_id, reagent_id, type, quantity, lot_number, expiry_date, production_date, note, operator, department, reason)
    values
      (p_tenant_id, reagent_row.id, p_type, item_quantity,
       coalesce(item->>'lot_number', ''), coalesce(item->>'expiry_date', ''),
       coalesce(item->>'production_date', ''), coalesce(item->>'note', ''),
       coalesce(p_operator, ''), coalesce(p_department, ''), coalesce(p_reason, ''));
    total := total + 1;
  end loop;
  return total;
end;
$$;

create or replace function public.create_restock_order(p_tenant_id uuid, p_note text)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  new_order public.purchase_orders;
  reagent_row public.reagents;
  target_quantity integer;
begin
  if not public.is_tenant_admin(p_tenant_id) then raise exception '只有检验科管理员可以创建采购单'; end if;
  insert into public.purchase_orders (tenant_id, status, note, item_count)
  values (p_tenant_id, 'submitted', coalesce(p_note, ''), 0) returning * into new_order;
  for reagent_row in
    select * from public.reagents
    where tenant_id = p_tenant_id and min_stock > 0 and stock_quantity <= min_stock
  loop
    target_quantity := greatest(reagent_row.min_stock * 2 - reagent_row.stock_quantity, 1);
    insert into public.purchase_order_items
      (tenant_id, order_id, reagent_id, quantity, unit, name, manufacturer, specification, supplier)
    values
      (p_tenant_id, new_order.id, reagent_row.id, target_quantity,
       reagent_row.unit, reagent_row.name, reagent_row.manufacturer, reagent_row.specification, reagent_row.supplier);
  end loop;
  update public.purchase_orders
    set item_count = (select count(*) from public.purchase_order_items where order_id = new_order.id and tenant_id = p_tenant_id)
    where id = new_order.id and tenant_id = p_tenant_id;
  return jsonb_build_object('id', new_order.id);
end;
$$;

create or replace function public.receive_purchase_order(p_tenant_id uuid, p_id bigint, p_operator text)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  order_row public.purchase_orders;
  item_row public.purchase_order_items;
begin
  if not public.is_tenant_admin(p_tenant_id) then raise exception '只有检验科管理员可以确认到货'; end if;
  select * into order_row from public.purchase_orders where id = p_id and tenant_id = p_tenant_id for update;
  if order_row.id is null then raise exception '采购单不存在'; end if;
  if order_row.status <> 'submitted' then return; end if;
  for item_row in select * from public.purchase_order_items where order_id = p_id and tenant_id = p_tenant_id loop
    update public.reagents set stock_quantity = stock_quantity + item_row.quantity
      where id = item_row.reagent_id and tenant_id = p_tenant_id;
    insert into public.stock_records (tenant_id, reagent_id, type, quantity, lot_number, note, operator, department, reason)
    values (p_tenant_id, item_row.reagent_id, 'in', item_row.quantity, '', '采购单到货', coalesce(p_operator, ''), '检验科', '采购入库');
  end loop;
  update public.purchase_orders set status = 'received' where id = p_id and tenant_id = p_tenant_id;
end;
$$;

