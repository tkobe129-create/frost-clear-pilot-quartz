-- 试剂资料通过受控 RPC 保存；期初库存以入库流水原子记录，编辑资料永远不改库存。
create or replace function public.save_reagent(
  p_tenant_id uuid,
  p_id bigint,
  p_reagent jsonb,
  p_initial_stock integer,
  p_operator text
)
returns public.reagents
language plpgsql security definer set search_path = public
as $$
declare
  saved public.reagents;
  opening_stock integer := coalesce(p_initial_stock, 0);
begin
  if not public.is_tenant_admin(p_tenant_id) then raise exception '只有检验科管理员可以保存试剂'; end if;
  if p_reagent is null or jsonb_typeof(p_reagent) is distinct from 'object' then raise exception '试剂资料格式错误'; end if;
  if opening_stock < 0 then raise exception '期初库存不能小于 0'; end if;

  if p_id is null then
    insert into public.reagents (
      tenant_id, code, name, category, specification, manufacturer, unit,
      stock_quantity, min_stock, storage_condition, location, expiry_date,
      registration_number, notes, scan_rule, scan_segments, lot_number,
      production_date, raw_barcode, supplier, unit_price
    ) values (
      p_tenant_id,
      coalesce(p_reagent->>'code', ''),
      coalesce(p_reagent->>'name', ''),
      coalesce(p_reagent->>'category', ''),
      coalesce(p_reagent->>'specification', ''),
      coalesce(p_reagent->>'manufacturer', ''),
      coalesce(p_reagent->>'unit', '盒'),
      0,
      coalesce(nullif(p_reagent->>'min_stock', '')::integer, 0),
      coalesce(p_reagent->>'storage_condition', ''),
      coalesce(p_reagent->>'location', ''),
      coalesce(p_reagent->>'expiry_date', ''),
      coalesce(p_reagent->>'registration_number', ''),
      coalesce(p_reagent->>'notes', ''),
      coalesce(p_reagent->>'scan_rule', ''),
      case when jsonb_typeof(p_reagent->'scan_segments') = 'array' then p_reagent->'scan_segments' else '[]'::jsonb end,
      coalesce(p_reagent->>'lot_number', ''),
      coalesce(p_reagent->>'production_date', ''),
      coalesce(p_reagent->>'raw_barcode', ''),
      coalesce(p_reagent->>'supplier', ''),
      coalesce(nullif(p_reagent->>'unit_price', '')::numeric, 0)
    ) returning * into saved;

    if opening_stock > 0 then
      update public.reagents set stock_quantity = opening_stock
        where id = saved.id and tenant_id = p_tenant_id returning * into saved;
      insert into public.stock_records (
        tenant_id, reagent_id, type, quantity, lot_number, expiry_date,
        production_date, note, operator, department, reason
      ) values (
        p_tenant_id, saved.id, 'in', opening_stock, saved.lot_number,
        saved.expiry_date, saved.production_date, '新建试剂期初库存',
        coalesce(nullif(p_operator, ''), '管理员'), '检验科', '期初库存'
      );
    end if;
    return saved;
  end if;

  if opening_stock <> 0 then raise exception '编辑试剂资料不能变更库存'; end if;
  update public.reagents set
    code = coalesce(p_reagent->>'code', ''),
    name = coalesce(p_reagent->>'name', ''),
    category = coalesce(p_reagent->>'category', ''),
    specification = coalesce(p_reagent->>'specification', ''),
    manufacturer = coalesce(p_reagent->>'manufacturer', ''),
    unit = coalesce(p_reagent->>'unit', '盒'),
    min_stock = coalesce(nullif(p_reagent->>'min_stock', '')::integer, 0),
    storage_condition = coalesce(p_reagent->>'storage_condition', ''),
    location = coalesce(p_reagent->>'location', ''),
    expiry_date = coalesce(p_reagent->>'expiry_date', ''),
    registration_number = coalesce(p_reagent->>'registration_number', ''),
    notes = coalesce(p_reagent->>'notes', ''),
    scan_rule = coalesce(p_reagent->>'scan_rule', ''),
    scan_segments = case when jsonb_typeof(p_reagent->'scan_segments') = 'array' then p_reagent->'scan_segments' else '[]'::jsonb end,
    lot_number = coalesce(p_reagent->>'lot_number', ''),
    production_date = coalesce(p_reagent->>'production_date', ''),
    raw_barcode = coalesce(p_reagent->>'raw_barcode', ''),
    supplier = coalesce(p_reagent->>'supplier', ''),
    unit_price = coalesce(nullif(p_reagent->>'unit_price', '')::numeric, 0)
  where id = p_id and tenant_id = p_tenant_id
  returning * into saved;
  if saved.id is null then raise exception '试剂不存在或不属于当前检验科'; end if;
  return saved;
end;
$$;

-- 返回完整库存台账汇总出的批次余量，不受前端“最近 200 条记录”显示上限影响。
create or replace function public.list_available_stock_batches(p_tenant_id uuid)
returns table (
  reagent_id bigint,
  lot_number text,
  expiry_date text,
  production_date text,
  quantity bigint
)
language plpgsql stable security definer set search_path = public
as $$
begin
  if p_tenant_id is null or not public.is_tenant_member(p_tenant_id) then
    raise exception '无权访问该检验科';
  end if;

  return query
  with tenant_reagents as (
    select r.id, r.lot_number, r.expiry_date, r.production_date, r.stock_quantity
    from public.reagents r
    where r.tenant_id = p_tenant_id
  ),
  batch_ledger as (
    select
      sr.reagent_id,
      sr.lot_number,
      sr.expiry_date,
      sr.production_date,
      sum(case when sr.type = 'in' then sr.quantity else -sr.quantity end)::bigint as quantity
    from public.stock_records sr
    where sr.tenant_id = p_tenant_id
      and (sr.lot_number <> '' or sr.expiry_date <> '')
    group by sr.reagent_id, sr.lot_number, sr.expiry_date, sr.production_date
  ),
  known_net as (
    select bl.reagent_id, sum(bl.quantity)::bigint as quantity
    from batch_ledger bl
    group by bl.reagent_id
  ),
  combined as (
    select bl.reagent_id, bl.lot_number, bl.expiry_date, bl.production_date, bl.quantity
    from batch_ledger bl
    union all
    select
      r.id,
      r.lot_number,
      r.expiry_date,
      r.production_date,
      (r.stock_quantity - coalesce(kn.quantity, 0))::bigint
    from tenant_reagents r
    left join known_net kn on kn.reagent_id = r.id
  )
  select c.reagent_id, c.lot_number, c.expiry_date, c.production_date, sum(c.quantity)::bigint
  from combined c
  group by c.reagent_id, c.lot_number, c.expiry_date, c.production_date
  having sum(c.quantity) > 0;
end;
$$;

create or replace function public.submit_stock_batch(
  p_tenant_id uuid, p_type text, p_operator text, p_department text, p_reason text, p_items jsonb
)
returns integer
language plpgsql security definer set search_path = public
as $$
declare
  item jsonb;
  reagent_row public.reagents;
  item_quantity integer;
  batch_lot text;
  batch_expiry text;
  batch_production text;
  batch_net bigint;
  known_net bigint;
  available_batch bigint;
  total integer := 0;
begin
  if not public.is_tenant_member(p_tenant_id) then raise exception '无权访问该检验科'; end if;
  if p_type is null or p_type not in ('in', 'out') then raise exception '无效的库存操作'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then raise exception '库存明细格式错误'; end if;

  for item in select * from jsonb_array_elements(p_items) loop
    item_quantity := (item->>'quantity')::integer;
    if item_quantity is null or item_quantity <= 0 then raise exception '数量必须大于 0'; end if;
    batch_lot := coalesce(item->>'lot_number', '');
    batch_expiry := coalesce(item->>'expiry_date', '');
    batch_production := coalesce(item->>'production_date', '');

    select * into reagent_row from public.reagents
      where id = (item->>'reagent_id')::bigint and tenant_id = p_tenant_id for update;
    if reagent_row.id is null then raise exception '试剂不存在或不属于当前检验科'; end if;

    if p_type = 'out' then
      if reagent_row.stock_quantity < item_quantity then
        raise exception '出库数量超过库存：%', reagent_row.name;
      end if;

      select coalesce(sum(case when sr.type = 'in' then sr.quantity else -sr.quantity end), 0)::bigint
      into batch_net
      from public.stock_records sr
      where sr.tenant_id = p_tenant_id
        and sr.reagent_id = reagent_row.id
        and (sr.lot_number <> '' or sr.expiry_date <> '')
        and sr.lot_number = batch_lot
        and sr.expiry_date = batch_expiry
        and sr.production_date = batch_production;

      select coalesce(sum(case when sr.type = 'in' then sr.quantity else -sr.quantity end), 0)::bigint
      into known_net
      from public.stock_records sr
      where sr.tenant_id = p_tenant_id
        and sr.reagent_id = reagent_row.id
        and (sr.lot_number <> '' or sr.expiry_date <> '');

      available_batch := batch_net;
      if batch_lot = reagent_row.lot_number
        and batch_expiry = reagent_row.expiry_date
        and batch_production = reagent_row.production_date then
        available_batch := available_batch + reagent_row.stock_quantity - known_net;
      end if;
      if available_batch < item_quantity then
        raise exception '所选批次库存不足：%', reagent_row.name;
      end if;
    end if;

    update public.reagents
      set stock_quantity = stock_quantity + case when p_type = 'in' then item_quantity else -item_quantity end
      where id = reagent_row.id and tenant_id = p_tenant_id;
    insert into public.stock_records
      (tenant_id, reagent_id, type, quantity, lot_number, expiry_date, production_date, note, operator, department, reason)
    values
      (p_tenant_id, reagent_row.id, p_type, item_quantity,
       batch_lot, batch_expiry, batch_production, coalesce(item->>'note', ''),
       coalesce(p_operator, ''), coalesce(p_department, ''), coalesce(p_reason, ''));
    total := total + 1;
  end loop;
  return total;
end;
$$;

create or replace function public.create_restock_order(p_tenant_id uuid, p_note text)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  new_order public.purchase_orders;
  reagent_row public.reagents;
  target_quantity integer;
begin
  if not public.is_tenant_admin(p_tenant_id) then raise exception '只有检验科管理员可以创建采购单'; end if;
  insert into public.purchase_orders (tenant_id, status, note, item_count)
  values (p_tenant_id, 'submitted', coalesce(p_note, ''), 0) returning * into new_order;
  for reagent_row in
    select * from public.reagents
    where tenant_id = p_tenant_id and min_stock > 0 and stock_quantity <= min_stock
  loop
    target_quantity := greatest(reagent_row.min_stock * 2 - reagent_row.stock_quantity, 1);
    insert into public.purchase_order_items
      (tenant_id, order_id, reagent_id, quantity, unit, name, manufacturer, specification, supplier)
    values
      (p_tenant_id, new_order.id, reagent_row.id, target_quantity,
       reagent_row.unit, reagent_row.name, reagent_row.manufacturer, reagent_row.specification, reagent_row.supplier);
  end loop;
  update public.purchase_orders
    set item_count = (select count(*) from public.purchase_order_items where order_id = new_order.id and tenant_id = p_tenant_id)
    where id = new_order.id and tenant_id = p_tenant_id;
  return jsonb_build_object('id', new_order.id);
end;
$$;

create or replace function public.receive_purchase_order(p_tenant_id uuid, p_id bigint, p_operator text)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  order_row public.purchase_orders;
  item_row public.purchase_order_items;
begin
  if not public.is_tenant_admin(p_tenant_id) then raise exception '只有检验科管理员可以确认到货'; end if;
  select * into order_row from public.purchase_orders where id = p_id and tenant_id = p_tenant_id for update;
  if order_row.id is null then raise exception '采购单不存在'; end if;
  if order_row.status <> 'submitted' then return; end if;
  for item_row in select * from public.purchase_order_items where order_id = p_id and tenant_id = p_tenant_id loop
    update public.reagents set stock_quantity = stock_quantity + item_row.quantity
      where id = item_row.reagent_id and tenant_id = p_tenant_id;
    insert into public.stock_records (tenant_id, reagent_id, type, quantity, lot_number, note, operator, department, reason)
    values (p_tenant_id, item_row.reagent_id, 'in', item_row.quantity, '', '采购单到货', coalesce(p_operator, ''), '检验科', '采购入库');
  end loop;
  update public.purchase_orders set status = 'received' where id = p_id and tenant_id = p_tenant_id;
end;
$$;

